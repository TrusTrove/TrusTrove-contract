#!/usr/bin/env python3
"""Generate and verify TypeScript client bindings from compiled Soroban WASM specs.

Usage:
    python3 scripts/generate_ts_bindings.py --write
    python3 scripts/generate_ts_bindings.py --check
    python3 scripts/generate_ts_bindings.py --write --from-source

By default, specs are decoded from the `contractspecv0` custom section of
compiled release WASM artifacts under `target/wasm32v1-none/release`.
"""
from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

from soroban_spec import (
    CONTRACTS,
    ROOT,
    ContractSpec,
    EnumSpec,
    FnSpec,
    StructSpec,
    TypeRef,
    UnionSpec,
    read_local_specs,
)

DEFAULT_WASM_DIR = ROOT / "target" / "wasm32v1-none" / "release"
DEFAULT_OUT_DIR = ROOT / "bindings" / "ts"

TS_PREAMBLE = """// AUTO-GENERATED by scripts/generate_ts_bindings.py — DO NOT EDIT.
// Regenerate with: python3 scripts/generate_ts_bindings.py --write

export type Address = string;
export type u32 = number;
export type i32 = number;
export type u64 = bigint;
export type i64 = bigint;
export type u128 = bigint;
export type i128 = bigint;
export type u256 = bigint;
export type i256 = bigint;
export type Bytes = Uint8Array;
export type BytesN<N extends number = number> = Uint8Array & { readonly __byteLength?: N };
export type Option<T> = T | undefined;
"""


def type_to_ts(t: TypeRef) -> str:
    """Convert a Soroban TypeRef into its TypeScript type representation."""
    if t.kind == "primitive":
        mapping = {
            "void": "void",
            "bool": "boolean",
            "u32": "u32",
            "i32": "i32",
            "u64": "u64",
            "i64": "i64",
            "u128": "u128",
            "i128": "i128",
            "u256": "u256",
            "i256": "i256",
            "Timepoint": "u64",
            "Duration": "u64",
            "Address": "Address",
            "MuxedAddress": "Address",
            "String": "string",
            "Symbol": "string",
            "Bytes": "Bytes",
            "Val": "unknown",
            "Error": "unknown",
        }
        return mapping.get(t.name, "unknown")
    if t.kind == "option":
        assert t.inner is not None
        return f"Option<{type_to_ts(t.inner)}>"
    if t.kind == "result":
        assert t.ok is not None and t.err is not None
        return f"{{ ok: {type_to_ts(t.ok)} }} | {{ err: {type_to_ts(t.err)} }}"
    if t.kind == "vec":
        assert t.inner is not None
        return f"Array<{type_to_ts(t.inner)}>"
    if t.kind == "map":
        assert t.key is not None and t.value is not None
        return f"Map<{type_to_ts(t.key)}, {type_to_ts(t.value)}>"
    if t.kind == "tuple":
        return "readonly [" + ", ".join(type_to_ts(el) for el in t.elements) + "]"
    if t.kind == "bytes_n":
        return f"BytesN<{t.length}>"
    if t.kind == "udt":
        return t.name
    raise ValueError(f"unsupported TypeRef kind: {t.kind}")


def _render_enum(enum: EnumSpec) -> list[str]:
    lines = [f"export enum {enum.name} {{"]
    for case in enum.cases:
        lines.append(f"  {case.name} = {case.value},")
    lines.append("}")
    return lines


def _render_union(union: UnionSpec) -> list[str]:
    lines = [f"export type {union.name} ="]
    for case in union.cases:
        if not case.types:
            lines.append(f'  | {{ tag: "{case.name}"; values?: void }}')
        else:
            inner = ", ".join(type_to_ts(t) for t in case.types)
            lines.append(f'  | {{ tag: "{case.name}"; values: readonly [{inner}] }}')
    lines[-1] = lines[-1] + ";"
    return lines


def _render_struct(struct: StructSpec) -> list[str]:
    lines = [f"export interface {struct.name} {{"]
    for field in struct.fields:
        lines.append(f"  {field.name}: {type_to_ts(field.type)};")
    lines.append("}")
    return lines


def _render_fn(fn: FnSpec) -> str:
    ret = type_to_ts(fn.output)
    if not fn.inputs:
        return f"  {fn.name}(): Promise<{ret}>;"
    params = "; ".join(f"{p.name}: {type_to_ts(p.type)}" for p in fn.inputs)
    return f"  {fn.name}(args: {{ {params} }}): Promise<{ret}>;"


def render_contract_ts(key: str, pascal_name: str, spec: ContractSpec) -> str:
    """Render deterministic TypeScript client definitions for one contract."""
    canon = spec.canonical(contract_pascal_name=pascal_name)
    sections: list[str] = [TS_PREAMBLE.rstrip(), f"// Contract: {key} ({pascal_name}Contract)"]

    for err_enum in canon.error_enums:
        sections.append("\n".join(_render_enum(err_enum)))
    for enum in canon.enums:
        sections.append("\n".join(_render_enum(enum)))
    for union in canon.unions:
        sections.append("\n".join(_render_union(union)))
    for struct in canon.structs:
        sections.append("\n".join(_render_struct(struct)))

    client_lines = [f"export interface {pascal_name}Client {{"]
    for fn in canon.functions:
        client_lines.append(_render_fn(fn))
    client_lines.append("}")
    sections.append("\n".join(client_lines))

    method_names = ", ".join(f'"{fn.name}"' for fn in canon.functions)
    sections.append(f"export const {key.upper()}_METHODS = [{method_names}] as const;")

    return "\n\n".join(sections) + "\n"


def render_index_ts(contracts: tuple[tuple[str, str, str, str], ...] = CONTRACTS) -> str:
    """Render barrel index.ts re-exporting all generated contract modules."""
    lines = [
        "// AUTO-GENERATED by scripts/generate_ts_bindings.py — DO NOT EDIT.",
        "// Regenerate with: python3 scripts/generate_ts_bindings.py --write",
        "",
    ]
    for key, pascal_name, _, _ in contracts:
        lines.append(f'export * as {pascal_name} from "./{key}";')
    names_union = " | ".join(f'"{key}"' for key, _, _, _ in contracts)
    lines.append("")
    lines.append(f"export type ContractName = {names_union};")
    return "\n".join(lines) + "\n"


def generate_all(
    wasm_dir: Path = DEFAULT_WASM_DIR,
    from_source: bool = False,
    root: Path = ROOT,
    contracts: tuple[tuple[str, str, str, str], ...] = CONTRACTS,
) -> dict[str, str]:
    """Generate mapping of relative filename -> TypeScript file content."""
    specs = read_local_specs(wasm_dir=wasm_dir, from_source=from_source, root=root, contracts=contracts)
    outputs: dict[str, str] = {}
    for key, pascal_name, _, _ in contracts:
        outputs[f"{key}.ts"] = render_contract_ts(key, pascal_name, specs[key])
    outputs["index.ts"] = render_index_ts(contracts)
    return outputs


def write_bindings(outputs: dict[str, str], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for filename, content in outputs.items():
        (out_dir / filename).write_text(content, encoding="utf-8")


def check_bindings(outputs: dict[str, str], out_dir: Path) -> list[str]:
    """Return a list of drift/missing file error messages."""
    errors: list[str] = []
    for filename, expected in outputs.items():
        target = out_dir / filename
        if not target.is_file():
            errors.append(f"missing generated binding: {target}")
            continue
        actual = target.read_text(encoding="utf-8")
        if actual != expected:
            diff = "".join(
                difflib.unified_diff(
                    actual.splitlines(keepends=True),
                    expected.splitlines(keepends=True),
                    fromfile=str(target),
                    tofile=f"generated/{filename}",
                    n=2,
                )
            )
            errors.append(f"stale binding: {target}\n{diff}")
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write generated TypeScript files")
    mode.add_argument("--check", action="store_true", help="fail if committed TypeScript files are stale")
    parser.add_argument("--wasm-dir", type=Path, default=DEFAULT_WASM_DIR, help="directory with compiled .wasm files")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR, help="output directory for .ts files")
    parser.add_argument(
        "--from-source",
        action="store_true",
        help="parse Rust sources instead of compiled WASM specs (fallback when WASM is not built)",
    )
    args = parser.parse_args(argv)

    try:
        outputs = generate_all(wasm_dir=args.wasm_dir, from_source=args.from_source)
    except (FileNotFoundError, OSError, ValueError) as exc:
        print(f"Error generating TypeScript bindings: {exc}", file=sys.stderr)
        return 2

    if args.write:
        write_bindings(outputs, args.out_dir)
        print(f"Generated {len(outputs)} TypeScript binding file(s) in {args.out_dir}.")
        return 0

    errors = check_bindings(outputs, args.out_dir)
    if errors:
        for err in errors:
            print(err, file=sys.stderr)
        print(
            "TypeScript client bindings are out of date; run "
            "python3 scripts/generate_ts_bindings.py --write",
            file=sys.stderr,
        )
        return 1

    print(f"All {len(outputs)} TypeScript client binding file(s) are up to date.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
